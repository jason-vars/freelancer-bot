// Copies ../userscript/freelancer-proposal-autofill.user.js into the app as a TS
// string, so the /userscript.user.js route can serve it from a Vercel function
// (files outside web/ aren't available at runtime). Runs before dev and build.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, "../../userscript/freelancer-proposal-autofill.user.js");
const out = resolve(here, "../src/generated/userscript-source.ts");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, "// Generated by scripts/embed-userscript.mjs — do not edit.\nexport const USERSCRIPT_SOURCE = " +
  JSON.stringify(readFileSync(src, "utf8")) + ";\n");
console.log("embedded userscript ->", out);
