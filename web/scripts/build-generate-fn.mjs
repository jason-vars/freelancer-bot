// Builds supabase/functions/generate/index.ts — the userscript's proposal endpoint
// as a Supabase Edge Function — from the web app's own code, so the two never drift.
// Run after changing proposal / pricing / filter / settings code:
//   npm run build:generate-fn      (in web/)
// then deploy the function (supabase/README in web/README.md, "Proposal function").
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync, rmSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "../..");
const src = resolve(repo, "supabase/generate-src");
const out = resolve(repo, "supabase/functions/generate/index.ts");
const tmp = resolve(src, ".bundle.js");
const pkg = JSON.parse(readFileSync(resolve(repo, "web/package.json"), "utf8")).dependencies;

execFileSync("npx", [
  "--yes", "esbuild@0.25.10", resolve(src, "entry.ts"),
  "--bundle", "--format=esm", "--platform=neutral", "--target=es2022",
  `--tsconfig=${resolve(src, "tsconfig.json")}`,
  "--external:openai", "--external:@supabase/supabase-js", "--external:node:*",
  `--outfile=${tmp}`, "--log-level=warning",
], { stdio: "inherit", shell: process.platform === "win32" });

// npm packages are loaded by Deno itself, at the web app's versions.
const code = readFileSync(tmp, "utf8")
  .replaceAll('from "openai"', `from "npm:openai@${pkg.openai}"`)
  .replaceAll('from "@supabase/supabase-js"', `from "npm:@supabase/supabase-js@${pkg["@supabase/supabase-js"]}"`);
rmSync(tmp);
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out,
  "// @ts-nocheck\n// GENERATED by web/scripts/build-generate-fn.mjs from the web app's code " +
  "(source: supabase/generate-src/entry.ts). Don't edit; rebuild.\n" + code);
console.log("built", out);
